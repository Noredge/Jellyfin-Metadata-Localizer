import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const web = path.join(repo, 'src/Localizer.Plugin/Web');
const modules = [
  'state.js', 'api.mjs', 'overview.mjs', 'movies.mjs', 'settings.mjs',
  'work.mjs', 'rules.mjs', 'lifecycle.mjs', 'i18n.mjs', 'events.js',
];
const read = (file) => fs.readFileSync(path.join(web, file), 'utf8').replaceAll('\r\n', '\n');

export function assemblePage() {
  // Authoring modules export named functions for tests. Delivery remains one page closure,
  // with no module loader, external assets or runtime build dependency in Jellyfin.
  const scripts = modules.map((file) => read('scripts/' + file).replace(/^export /gm, '')).join('\n');
  return '<!-- Generated by scripts/Build-Web.mjs; edit Web/page.html, styles.css or scripts/. -->\n'
    + read('page.html').replace('/*__LOCALIZER_STYLE__*/', () => read('styles.css'))
      .replace('/*__LOCALIZER_SCRIPT__*/', () => '(() => {\n' + scripts + '\n})();');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = path.join(web, 'unified.html');
  const expected = assemblePage();
  if (process.argv.includes('--write')) fs.writeFileSync(target, expected, 'utf8');
  else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== expected) {
    throw new Error('Embedded page is stale. Run node scripts/Build-Web.mjs --write.');
  }
  console.log('PASS embedded page matches its readable sources');
}
